const assert = require("assert");
const K = require("../src/infant-symbolic-kernel.js");
const s = K.create();
assert.strictEqual(K.VERSION, "0.3.0-recurrent-attention");
assert.ok(Math.abs(K.l1(s.brain_field) - 1) < 1e-6);
assert.ok(Math.abs(K.l1(s.body.body_field) - 1) < 1e-6);
K.step(s, "abababab cdcdcdcd ababab cdcdcdcd");
assert.ok(s.memory.token_library.length > 0);
assert.ok(s.memory.token_relation_graph.length > 0);
assert.ok(s.internal_math_packet.token_count > 0);
assert.ok(s.internal_math_packet.relation_count > 0);
assert.ok(Math.abs(s.internal_math_packet.token_l1 - 1) < 1e-6);
assert.ok(Math.abs(s.internal_math_packet.relation_l1 - 1) < 1e-6);
assert.ok(Math.abs(K.l1(s.attention_field) - 1) < 1e-6);
assert.ok(Math.abs(K.l1(s.thought_field) - 1) < 1e-6);
const beforeCycles = s.thought_state.cycle_count;
K.think(s, 4);
assert.ok(s.thought_state.cycle_count > beforeCycles);
assert.ok(s.thought_state.candidates.length > 0);
const settled = K.settle(s);
assert.ok(settled.selected);
const action = K.act(s);
assert.ok(action.enabled);
assert.strictEqual(action.english, "");
assert.strictEqual(s.english_expression_channel.enabled, false);
K.observe(s, "xxxx yyyy xxxx yyyy");
assert.ok(s.sensory.raw.includes("xxxx"));
assert.ok(Math.abs(K.l1(s.brain_field) - 1) < 1e-6);
assert.ok(Math.abs(K.l1(s.body.body_field) - 1) < 1e-6);
console.log("PASS infant v03 recurrent attention smoke test");
